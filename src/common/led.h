#pragma once
#include <Arduino.h>

/**
 * 板载 RGB 灯(GPIO48 WS2812)。
 *
 * ══════════════════════════════════════════════════════════════════════
 *  三种模式(互斥)
 *
 *    ① 自动(默认)  —— 灯反映板子状态:
 *                        未连接 = 暗蓝 / 已连接 = 暗绿 / 执行中 = 暗黄
 *    ② 手动色       —— 用户指定颜色,**一直保持**,状态变化也不会被盖掉
 *    ③ 找板子       —— 快-快-慢闪 + 绿色常亮 60 秒,然后回到自动
 *
 *  ⚠️ 为什么要有"手动色"这个模式:
 *      最早 set() 只是写颜色,没标记"被手动接管"。
 *      结果:手动设了红色,手机一连上,状态色就把它盖成绿色了 ——
 *      用户看着莫名其妙。所以手动色必须**锁住**,要显式 `autoMode()` 才交还。
 * ══════════════════════════════════════════════════════════════════════
 */
namespace Led {

/** 初始化(上电闪一下,表示固件起来了) */
void begin();

/**
 * 设颜色并保持。
 *
 * @param holdMs 0 = **一直保持**(手动模式,状态色不会盖它)
 *                >0 = 只亮这么久,到点**自动**回到状态色
 */
void set(uint8_t r, uint8_t g, uint8_t b, uint32_t holdMs = 0);

/** 关灯(= set(0,0,0,0),同样会锁住,不会被状态色点亮) */
void off();

/** 回到「自动」模式:灯重新反映板子状态 */
void autoMode();

/** 当前是不是手动接管中(给 /api/status 用) */
bool isManual();

/** 「找板子」模式:快-快-慢闪 + 绿色常亮 60 秒,然后回自动 */
void identify();

/** 主循环里调 —— 处理"保持时间到了,回到自动" */
void tick();

/**
 * 板子的四种状态 —— 状态灯按这个变色。
 *
 * 需求明确要求:
 *   待机(已连接、没在跑) → **红**
 *   运行中               → **黄**
 *   执行结束             → **绿**(亮几秒,然后回待机红)
 *   闲置(手机没连)       → **灭**
 */
enum State {
  ST_OFF     = 0,   // 闲置:没有手机连接 → 灭
  ST_IDLE    = 1,   // 待机:连着但没跑     → 红
  ST_RUNNING = 2,   // 运行中              → 黄
  ST_DONE    = 3,   // 刚跑完(由 finished() 自动进入,几秒后回待机)
};

/** 按状态改灯(自动模式用) */
void setState(int state);

/** 老接口,等价于 setState()。保留是为了不破坏已有调用 */
void setStateColor(int state);

/** 流程执行结束 —— 亮绿色几秒再回待机 */
void finished();

/**
 * 四色轮播自检:红 → 黄 → 绿 → 灭,每个 1.5 秒,走完自动回"自动"模式。
 *
 * ⚠️ 为什么要这个:
 *      现场很难确认"灯到底有没有按状态变色" —— 尤其黄只亮流程那么久(2~3 秒),
 *      绿 5 秒,错过就以为灯坏了。这个自检把四个颜色**依次**亮一遍,
 *      一眼就能确认灯和引脚都是对的。
 *
 * 从串口 / 蓝牙控制通道 / HTTP 都能触发(LEDTEST / LED TEST)。
 */
void colorTest();

/** 是不是正在自检 */
bool testing();

/** 当前是不是还在 identify 模式 */
bool identifying();

/** 一行文本描述,给接口/日志用 */
const char *modeName();

}  // namespace Led
